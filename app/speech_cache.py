"""
Spoken clips, kept for a while so a reply can be heard again.

A clip is a pure function of what was said and how it was voiced, so it is kept under
a hash of exactly that: the speech provider (its row and its address), the model, the
voice, and the words. Nothing about the turn, the thread or the device is in the key,
which is what makes replay work anywhere: any window holding a reply's text cuts it
the way the live stream did (``speakableSegments`` in web/js/segments.js), asks for
each segment, and gets back the clips that were already paid for. A segment that is
not here (expired, never made, or failed the first time) is simply made again.

**Kept per user, by path**, the same way attachments are:
``data/speech/<user id>/<sha256>.<ext>``. The directory is the ownership check. Two
users with the same voice saying the same words get a file each, because the key is
only ever looked up in the caller's own folder.

**This is conversation-derived data kept on the server**, which nothing else in this
service does. It is a cache and nothing more: it expires, and
``speech.cache_ttl_hours: 0`` turns it off and clears what was kept at the next start.
The response still says ``no-store``, so no browser or proxy keeps a copy as well.

**The age is since last heard**, not since made. A reply somebody keeps replaying stays;
one nobody has asked for in a week goes. Unlike the picture stores, a sweep here is
always safe: the worst it can do is cost one more synthesis.
"""

import hashlib
import json
import logging
import os
import re
import tempfile
import time
from pathlib import Path

from app import config

logger = logging.getLogger(__name__)

#: A week. Long enough that a paid voice is not bought twice for a reply re-read the
#: next evening; short enough that the server is not an archive of everything said.
DEFAULT_TTL_HOURS = 168

#: How often one user's folder is swept while the service is running. Per process, in
#: memory: a restart sweeps everything anyway.
SWEEP_EVERY_SECONDS = 3600

#: The audio types a clip is kept as. Anything else is played and not kept, because a
#: file whose type cannot be told from its name could not be served back correctly.
EXTENSIONS = {
    "audio/mpeg": "mp3",
    "audio/mp3": "mp3",
    "audio/wav": "wav",
    "audio/x-wav": "wav",
    "audio/wave": "wav",
    "audio/ogg": "ogg",
    "audio/opus": "opus",
    "audio/flac": "flac",
    "audio/aac": "aac",
    "audio/webm": "webm",
}
CONTENT_TYPES = {
    "mp3": "audio/mpeg",
    "wav": "audio/wav",
    "ogg": "audio/ogg",
    "opus": "audio/opus",
    "flac": "audio/flac",
    "aac": "audio/aac",
    "webm": "audio/webm",
}

_KEY = re.compile(r"^[0-9a-f]{64}$")
_USER = re.compile(r"^[A-Za-z0-9-]{1,64}$")

#: user id -> when their folder was last swept.
_last_swept: dict[str, float] = {}


def directory() -> Path:
    """Where clips live. Read per call so a test can point it somewhere else."""
    return Path(os.getenv("WEFT_SPEECH_DIR", "data/speech"))


def ttl_seconds() -> int:
    """How long an unheard clip is kept. 0 means the cache is off."""
    try:
        hours = float(config.get("speech.cache_ttl_hours", DEFAULT_TTL_HOURS))
    except (TypeError, ValueError):
        hours = DEFAULT_TTL_HOURS
    return max(0, int(hours * 3600))


def enabled() -> bool:
    return ttl_seconds() > 0


def key_for(*, provider_id: str, base_url: str, model: str, voice: str, text: str) -> str:
    """The name a clip is kept under. JSON, so no field can run into the next."""
    material = json.dumps([provider_id, base_url, model, voice, text], ensure_ascii=False)
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def user_folder(user_id: str) -> Path:
    if not _USER.match(user_id):
        # User ids are generated by this server; anything else is a bug, not input.
        raise ValueError("unexpected user id shape")
    return directory() / user_id


def _ours(entry: Path) -> bool:
    """Only names this module writes. Anything else in the folder is somebody else's."""
    return _KEY.match(entry.stem) is not None and entry.suffix[1:] in CONTENT_TYPES


def fetch(user_id: str, key: str) -> tuple[str, bytes] | None:
    """``(content_type, audio)`` for a kept clip, or None. Blocking: run in a threadpool.

    A hit refreshes the clip's age. An expired clip is removed and counts as a miss.
    """
    if not enabled() or not _KEY.match(key):
        return None
    folder = user_folder(user_id)
    cutoff = time.time() - ttl_seconds()
    for ext, content_type in CONTENT_TYPES.items():
        path = folder / f"{key}.{ext}"
        try:
            if path.stat().st_mtime < cutoff:
                path.unlink(missing_ok=True)
                return None
            audio = path.read_bytes()
            os.utime(path)
        except FileNotFoundError:
            continue
        except OSError:
            logger.warning("Could not read kept clip %s.", path, exc_info=True)
            return None
        return content_type, audio
    return None


def keep(user_id: str, key: str, content_type: str, audio: bytes) -> None:
    """Keep a clip under its key. Blocking: run in a threadpool. Never raises.

    Atomic, written beside its final name and renamed, so a reader on another device
    never gets half a clip. A failure is logged and dropped: the clip already reached
    the person who asked for it, and a cache that cannot write is only a slower cache.
    """
    ext = EXTENSIONS.get(content_type)
    if not enabled() or ext is None or not _KEY.match(key):
        return
    try:
        folder = user_folder(user_id)
        folder.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=folder, suffix=".part")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(audio)
            os.replace(tmp, folder / f"{key}.{ext}")
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
    except Exception:
        logger.warning("Could not keep a spoken clip for user %s.", user_id, exc_info=True)
        return
    _maybe_sweep(user_id)


def _sweep_folder(folder: Path, cutoff: float) -> int:
    removed = 0
    for entry in folder.iterdir():
        try:
            if entry.suffix == ".part":
                # A write that died half way. An hour is far longer than any write.
                if entry.stat().st_mtime < time.time() - SWEEP_EVERY_SECONDS:
                    entry.unlink(missing_ok=True)
                continue
            if _ours(entry) and entry.stat().st_mtime < cutoff:
                entry.unlink(missing_ok=True)
                removed += 1
        except OSError:
            continue
    return removed


def _maybe_sweep(user_id: str) -> None:
    now = time.time()
    if now - _last_swept.get(user_id, 0) < SWEEP_EVERY_SECONDS:
        return
    _last_swept[user_id] = now
    try:
        _sweep_folder(user_folder(user_id), now - ttl_seconds())
    except OSError:
        logger.warning("Could not sweep kept clips for user %s.", user_id, exc_info=True)


def sweep() -> int:
    """Remove every expired clip, for every user. Returns how many went.

    Run at startup. With the cache off (a TTL of 0) the cutoff is now, so everything
    that was kept goes: turning it off means nothing stays. Blocking: run in a
    threadpool. Never raises.
    """
    root = directory()
    if not root.is_dir():
        return 0
    cutoff = time.time() - ttl_seconds() if enabled() else float("inf")
    removed = 0
    try:
        for folder in root.iterdir():
            if folder.is_dir() and _USER.match(folder.name):
                removed += _sweep_folder(folder, cutoff)
    except OSError:
        logger.warning("Could not sweep kept clips.", exc_info=True)
    if removed:
        logger.info("Removed %d expired spoken clip(s).", removed)
    return removed
